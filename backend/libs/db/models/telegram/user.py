"""SQLAlchemy Core models: telegram users (peer identity)."""

from __future__ import annotations

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    Index,
    Integer,
    PrimaryKeyConstraint,
    Table,
    Text,
    UniqueConstraint,
    Uuid,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB

from db.metadata import metadata

telegram_users = Table(
    "telegram_users",
    metadata,
    Column("id", Uuid, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("external_id", Text, nullable=False),
    Column("access_hash", BigInteger),
    Column("first_name", Text),
    Column("last_name", Text),
    Column("username", Text),
    Column("name_search", Text),
    Column("username_search", Text),
    Column("phone", Text),
    Column("photo", JSONB),
    Column("bot", Boolean, server_default=text("false")),
    Column("verified", Boolean, server_default=text("false")),
    Column("restricted", Boolean, server_default=text("false")),
    Column("scam", Boolean, server_default=text("false")),
    Column("fake", Boolean, server_default=text("false")),
    Column("premium", Boolean, server_default=text("false")),
    Column("restriction_reason", JSONB),
    Column("lang_code", Text),
    Column("emoji_status", JSONB),
    Column("settings", JSONB),
    Column("notify_settings", JSONB),
    Column("common_chats_count", Integer),
    Column("blocked", Boolean),
    Column("phone_calls_available", Boolean),
    Column("phone_calls_private", Boolean),
    Column("can_pin_message", Boolean),
    Column("has_scheduled", Boolean),
    Column("video_calls_available", Boolean),
    Column("voice_messages_forbidden", Boolean),
    Column("translations_disabled", Boolean),
    Column("stories_pinned_available", Boolean),
    Column("blocked_my_stories_from", JSONB),
    Column("wallpaper_overridden", Boolean),
    Column("contact_require_premium", Boolean),
    Column("read_dates_private", Boolean),
    Column("sponsored_enabled", Boolean),
    Column("can_view_revenue", Boolean),
    Column("bot_can_manage_emoji_status", Boolean),
    Column("display_gifts_button", Boolean),
    Column("about", Text),
    Column("personal_photo", JSONB),
    Column("profile_photo", JSONB),
    Column("fallback_photo", JSONB),
    Column("bot_info", JSONB),
    Column("pinned_msg_id", Integer),
    Column("folder_id", Integer),
    Column("ttl_period", Integer),
    Column("theme", JSONB),
    Column("private_forward_name", Text),
    Column("bot_group_admin_rights", JSONB),
    Column("bot_broadcast_admin_rights", JSONB),
    Column("wallpaper", JSONB),
    Column("stories", JSONB),
    Column("business_work_hours", JSONB),
    Column("business_location", JSONB),
    Column("business_greeting_message", Text),
    Column("business_away_message", Text),
    Column("business_intro", JSONB),
    Column("birthday", JSONB),
    Column("personal_channel_id", BigInteger),
    Column("personal_channel_message", Text),
    Column("stargifts_count", Integer),
    Column("starref_program", JSONB),
    Column("bot_verification", JSONB),
    Column("send_paid_messages_stars", BigInteger),
    Column("disallowed_gifts", JSONB),
    Column("stars_rating", JSONB),
    Column("stars_my_pending_rating", JSONB),
    Column("stars_my_pending_rating_date", Integer),
    Column("main_tab", JSONB),
    Column("saved_music", JSONB),
    Column("note", Text),
    Column("created_at", DateTime(True), nullable=False, server_default=text("now()")),
    Column("updated_at", DateTime(True), nullable=False, server_default=text("now()")),
    Column("profile_photo_s3_uri", Text),
    Column("engagement_count", Integer, nullable=False, server_default=text("0")),
    Column("unavailable_at", DateTime(True)),
    Column("pinned_stories", JSONB),
    Column("pinned_stories_fetched_at", DateTime(True)),
    Column("saved_star_gifts", JSONB),
    Column("star_gifts_fetched_at", DateTime(True)),
    Column("deleted", Boolean, nullable=False, server_default=text("false")),
    Column("deleted_observed_at", DateTime(True)),
    PrimaryKeyConstraint("id", name="telegram_users_pkey"),
    UniqueConstraint("external_id", name="telegram_users_peer_id_key"),
    Index(
        "telegram_users_username_search_trgm_idx",
        "username_search",
        postgresql_using="gin",
        postgresql_ops={"username_search": "gin_trgm_ops"},
    ),
    # Must match search_users_by_name WHERE clause for index use.
    Index(
        "telegram_users_name_search_trgm_idx",
        "name_search",
        postgresql_using="gin",
        postgresql_ops={"name_search": "gin_trgm_ops"},
    ),
    # Exact /search/username (lower(username) = %s); see alembic e3b7c1a9d4f0.
    Index(
        "telegram_users_username_lower_idx",
        text("lower(username)"),
        postgresql_where=text("username IS NOT NULL"),
    ),
    comment="User: id = our UUID, peer_id = Telegram user id",
)
