"""SQLAlchemy Core models: telegram channels."""

from __future__ import annotations

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    Index,
    Integer,
    PrimaryKeyConstraint,
    Table,
    Text,
    UniqueConstraint,
    Uuid,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB

from db.metadata import metadata

telegram_channels = Table(
    "telegram_channels",
    metadata,
    Column("id", Uuid, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("external_id", Text, nullable=False),
    Column("title", Text, nullable=False),
    Column("username", Text),
    Column("title_search", Text),
    Column("username_search", Text),
    Column("usernames_search", Text),
    Column("photo", JSONB),
    Column("date", DateTime(True), nullable=False),
    Column("is_broadcast", Boolean),
    Column("is_verified", Boolean),
    Column("is_megagroup", Boolean),
    Column("is_restricted", Boolean),
    Column("signatures", Boolean),
    Column("is_scam", Boolean),
    Column("has_link", Boolean),
    Column("has_geo", Boolean),
    Column("slowmode_enabled", Boolean),
    Column("is_forum", Boolean),
    Column("noforwards", Boolean),
    Column("join_to_send", Boolean),
    Column("join_request", Boolean),
    Column("restriction_reason", JSONB, server_default=text("'[]'::jsonb")),
    Column("default_banned_rights", JSONB),
    Column("participants_count", Integer),
    Column("usernames", JSONB, server_default=text("'[]'::jsonb")),
    Column("about", Text),
    Column("bot_info", JSONB, server_default=text("'[]'::jsonb")),
    Column("hidden_prehistory", Boolean),
    Column("antispam", Boolean),
    Column("participants_hidden", Boolean),
    Column("translations_disabled", Boolean),
    Column("stories_pinned_available", Boolean),
    Column("view_forum_as_messages", Boolean),
    Column("restricted_sponsored", Boolean),
    Column("paid_media_allowed", Boolean),
    Column("paid_reactions_available", Boolean),
    Column("stargifts_available", Boolean),
    Column("paid_messages_available", Boolean),
    Column("admins_count", Integer),
    Column("kicked_count", Integer),
    Column("banned_count", Integer),
    Column("online_count", Integer),
    Column("migrated_from_chat_id", BigInteger),
    Column("migrated_from_max_id", Integer),
    Column("pinned_msg_id", Integer),
    Column("stickerset", JSONB),
    Column("available_min_id", Integer),
    Column("first_message_at", DateTime(True)),
    Column("linked_chat_id", BigInteger),
    Column("location", JSONB),
    Column("slowmode_seconds", Integer),
    Column("slowmode_next_send_date", DateTime(True)),
    Column("stats_dc", Integer),
    Column("ttl_period", Integer),
    Column("theme_emoticon", Text),
    Column("available_reactions", JSONB),
    Column("reactions_limit", Integer),
    Column("wallpaper", JSONB),
    Column("boosts_applied", Integer),
    Column("emojiset", JSONB),
    Column("bot_verification", JSONB),
    Column("stargifts_count", Integer),
    Column("send_paid_messages_stars", BigInteger),
    Column("created_at", DateTime(True), nullable=False, server_default=text("now()")),
    Column("updated_at", DateTime(True), nullable=False, server_default=text("now()")),
    Column("profile_photo_s3_uri", Text),
    Column("language", Text),
    Column("harvester_id", Uuid),
    Column("is_gigagroup", Boolean),
    Column("is_monoforum", Boolean),
    Column("is_fake", Boolean),
    Column("stories_unavailable", Boolean),
    Column("stories_max_id", Integer),
    Column("signature_profiles", Boolean),
    Column("autotranslation", Boolean),
    Column("broadcast_messages_allowed", Boolean),
    Column("linked_monoforum_id", BigInteger),
    Column("color", JSONB),
    Column("profile_color", JSONB),
    Column("emoji_status", JSONB),
    Column("level", Integer),
    Column("bot_verification_icon", BigInteger),
    Column("boosts_unrestrict", Integer),
    Column("unavailable_at", DateTime(True)),
    #: Set when ``t.me/s/{username}`` is not a usable public message stream.
    Column("web_s_inaccessible_at", DateTime(True)),
    Column("similar_channels", JSONB, nullable=False, server_default=text("'[]'::jsonb")),
    Column("profile_tier", Text, nullable=False, server_default=text("'tg_full'::text")),
    CheckConstraint(
        "profile_tier = ANY (ARRAY['tg_full'::text, 'tg_min'::text, 'web'::text])",
        name="telegram_channels_profile_tier_check",
    ),
    PrimaryKeyConstraint("id", name="telegram_channels_pkey"),
    UniqueConstraint("external_id", name="telegram_channels_peer_id_key"),
    Index(
        "telegram_channels_title_search_trgm_idx",
        "title_search",
        postgresql_using="gin",
        postgresql_ops={"title_search": "gin_trgm_ops"},
    ),
    Index(
        "telegram_channels_username_search_trgm_idx",
        "username_search",
        postgresql_using="gin",
        postgresql_ops={"username_search": "gin_trgm_ops"},
    ),
    Index(
        "telegram_channels_usernames_search_trgm_idx",
        "usernames_search",
        postgresql_using="gin",
        postgresql_ops={"usernames_search": "gin_trgm_ops"},
    ),
    # Exact /search/username (lower(username) = %s); see alembic e3b7c1a9d4f0.
    Index(
        "telegram_channels_username_lower_idx",
        text("lower(username)"),
        postgresql_where=text("username IS NOT NULL"),
    ),
    comment="Channel/megagroup: id = our UUID, peer_id = Telegram channel id",
)
